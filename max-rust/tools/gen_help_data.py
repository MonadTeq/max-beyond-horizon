"""Generate `max_app/data/help.json` from the C++ port's help resources.

Source of truth (oracle, do not edit):
  * `max-cpp-port/assets/help.json` — `Help::LoadFile` schema: sections →
    entries `{coordinates, text{lang}}`; the port resolves the entry under the
    help cursor (`HelpMenu`).
  * `max-cpp-port/assets/language.json` — `_(ceb6)` keys/controls help text.

The Rust client opens a help window from a button (there is no help-cursor
mode in the SDL-less UI), so a screen shows the whole section: every non-empty
entry text of the section in file order (the order the original help authors
wrote, which reads as intended; C++ stores sections in an unordered map and
only ever shows one entry, so order never affected the original UI).

Usage (from the repository root):
    python max-rust/tools/gen_help_data.py

Do not hand-edit the generated file.
"""

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
HELP_SOURCE = ROOT / "max-cpp-port" / "assets" / "help.json"
LANGUAGE_SOURCE = ROOT / "max-cpp-port" / "assets" / "language.json"
OUTPUT = ROOT / "max-rust" / "crates" / "max_app" / "data" / "help.json"

KEYS_LANGUAGE_KEY = "ceb6"  # HelpMenu "Keys" text (GAME_SCREEN_SETUP)


def main() -> None:
    help_doc = json.loads(HELP_SOURCE.read_text(encoding="utf-8"))["help"]
    language = json.loads(LANGUAGE_SOURCE.read_text(encoding="utf-8"))["language"]

    sections = {}
    for name in sorted(help_doc):
        entries = []
        for entry_name, entry in help_doc[name].items():
            text = entry["text"].get("en-US", "")
            if not text:
                continue
            coords = entry["coordinates"]
            entries.append(
                {
                    "name": entry_name,
                    "ux": coords["ux"],
                    "uy": coords["uy"],
                    "lx": coords["lx"],
                    "ly": coords["ly"],
                    "text": text,
                }
            )
        if entries:
            sections[name] = entries

    keys_text = language[KEYS_LANGUAGE_KEY]["en-US"]

    document = {
        "$comment": (
            "Generated by max-rust/tools/gen_help_data.py from "
            "max-cpp-port/assets/help.json + assets/language.json. Do not edit by hand."
        ),
        "keys": keys_text,
        "sections": sections,
    }

    OUTPUT.write_text(
        json.dumps(document, ensure_ascii=False, indent=1) + "\n", encoding="utf-8"
    )
    total = sum(len(entries) for entries in sections.values())
    print(f"{OUTPUT}: {len(sections)} sections, {total} entries")


if __name__ == "__main__":
    main()
