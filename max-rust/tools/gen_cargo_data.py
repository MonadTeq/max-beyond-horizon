# Флаги (`Unit::Flags`, max-cpp-port/src/unit.cpp).
FLAG_GROUND_COVER = 0x1
FLAG_BUILDING = 0x10
FLAG_MOBILE_AIR = 0x40
FLAG_MOBILE_SEA = 0x80
FLAG_MOBILE_LAND = 0x100
FLAG_STATIONARY = 0x200
FLAG_UPGRADABLE = 0x4000

FLAG_NAMES = {
    "GROUND_COVER": FLAG_GROUND_COVER,
    "BUILDING": FLAG_BUILDING,
    "MOBILE_AIR_UNIT": FLAG_MOBILE_AIR,
    "MOBILE_SEA_UNIT": FLAG_MOBILE_SEA,
    "MOBILE_LAND_UNIT": FLAG_MOBILE_LAND,
    "STATIONARY": FLAG_STATIONARY,
    "UPGRADABLE": FLAG_UPGRADABLE,
}


def read_res(path, wanted):
    data = open(path, "rb").read()
    magic, offset, size = struct.unpack_from("<4sii", data, 0)
    assert magic == b"RES0", magic
    out = {}
    for i in range(size // 16):
        tag, o, s = struct.unpack_from("<8sii", data, offset + i * 16)
        name = tag.rstrip(b"\0").decode("latin-1")
        if name in wanted:
            blob = bytes(b ^ XOR_TABLE[j % 32] for j, b in enumerate(data[o:o + s]))
            out[name] = json.loads(blob.decode("utf-8"))
    missing = wanted - set(out)
    assert not missing, f"нет ресурсов: {missing}"
    return out


def unit_index(token):
    return UNIT_TOKENS.index(token)


def main():
    root = Path(__file__).resolve().parents[2]
    sys.path.insert(0, str(Path(__file__).resolve().parent))

    resources = read_res(root / "assets" / "PATCHES.RES", {"SC_UNITS", "SC_ATTRI"})
    units = resources["SC_UNITS"]["units"]
    attributes = resources["SC_ATTRI"]["attributes"]
    assert len(units) == UNIT_END, len(units)

    lines = [
        "// Generated by max-rust/tools/gen_cargo_data.py - do not edit by hand.",
        "// Source: assets/PATCHES.RES items SC_UNITS/SC_ATTRI + default.game_rules.lua",
        f"static const int kUnitCount = {UNIT_END};",
        "",
        "struct UnitData {",
        "    unsigned flags;",
        "    int turns, hits, armor, attack, speed, range, rounds, scan, storage, ammo;",
        "};",
        "",
        "static const UnitData kUnits[kUnitCount] = {",
    ]

    for token in UNIT_TOKENS:
        unit = units[token]
        raw_flags = 0
        for flag in unit["flags"]:
            raw_flags |= FLAG_NAMES.get(flag, 0)
        attr = attributes[token]
        fields = [
            attr["Turns to build"],
            min(attr["Hit points"], 0xFFFF),
            attr["Armor rating"],
            attr["Attack rating"],
            min(attr["Movement points"], 0xFFFF),
            attr["Attack range"],
            attr["Shots per turn"],
            attr["Scan range"],
            attr["Storage capacity"],
            attr["Ammunition"],
        ]
        # ATTRIB_* порядок в UnitValues: turns, hits, armor, attack, speed, range,
        # rounds, scan, storage, ammo.
        lines.append(
            "    {0x%04X, %s}, // %s" % (raw_flags, ", ".join(str(v) for v in fields), token)
        )

    lines += ["};", "", "// max_builder_capability_list: пары (строитель, что строит).", "struct BuildableEntry { int builder; int unit; };", "static const BuildableEntry kBuildable[] = {"]
    for builder, units_list in BUILDERS.items():
        for unit in units_list:
            lines.append("    {%d, %d}, // %s -> %s" % (unit_index(builder), unit_index(unit), builder, unit))
    lines += ["};", "static const int kBuildableCount = sizeof(kBuildable) / sizeof(kBuildable[0]);", ""]

    out = Path(__file__).resolve().parent / "cargo_vectors" / "data.inc"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"written {out} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
