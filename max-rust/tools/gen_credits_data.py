"""Генератор таблицы титров экрана `Credits` (`menu_credits_menu_loop`).

Оракул — `max-cpp-port/src/menu.cpp` (`menu_credits_menu_loop`, массив
`menu_credits_lines[]`):

```c
const struct CreditsLine menu_credits_lines[] = {
    CREDITS_TITLE(_(0a6f)),
    CREDITS_TEXT("Ali Atabek"),
    CREDITS_SEPARATOR,
    ...
};
```

* `CREDITS_TITLE(_(hex))` — заголовок раздела: hex-ключ `assets/language.json`
  (`Language::GetEntry`, строка `en-US`), цвет `0xFF`;
* `CREDITS_TEXT("…")` — строка-литерал как в C++ (не локализуется), цвет `0x04`;
* `CREDITS_SEPARATOR` — пустая строка (в C++ `{0x00, ""}`): `Text_TextBox` на
  пустой строке ничего не рисует, поэтому в JSON не попадает.

Вывод — `max-rust/crates/max_app/data/credits.json` (коммитится; крейт читает
его через `include_str!`). Скролл/раскладку задаёт `max_app::credits`.

Запуск (из корня репозитория):

    python max-rust/tools/gen_credits_data.py
"""

import json
import re
import sys
from pathlib import Path

PREFIX = {
    "TITLE": (0xFF, "title"),
    "TEXT": (0x04, "text"),
    "SEPARATOR": (0x00, "separator"),
}

ENTRY = re.compile(
    r"""^\s*CREDITS_(TITLE|TEXT|SEPARATOR)\s*(?:\(\s*(?:_\(([0-9a-fA-F]{1,4})\)|"(.*)")\s*\))?\s*,?\s*$"""
)


def extract_block(source: str) -> list[str]:
    start = source.index("menu_credits_lines[] = {")
    start = source.index("{", start) + 1
    end = source.index("};", start)

    return source[start:end].splitlines()


def decode_literal(text: str) -> str:
    # C++-литералы в таблице простые: экранируются только кавычки и слэши.
    return text.replace('\\"', '"').replace("\\\\", "\\")


def main() -> int:
    root = Path(__file__).resolve().parents[2]
    source = (root / "max-cpp-port" / "src" / "menu.cpp").read_text(encoding="utf-8")
    language = json.loads((root / "assets" / "language.json").read_text(encoding="utf-8"))["language"]

    lines = []
    counts = {"title": 0, "text": 0, "separator": 0}

    for raw in extract_block(source):
        raw = raw.split("//")[0].strip()

        if not raw:
            continue

        match = ENTRY.match(raw)

        if not match:
            raise SystemExit(f"не разобрана строка таблицы титров: {raw!r}")

        kind, hex_key, literal = match.groups()

        if kind == "SEPARATOR":
            counts["separator"] += 1
            continue

        if kind == "TITLE":
            key = format(int(hex_key, 16), "04x")
            entry = language.get(key)

            if entry is None:
                raise SystemExit(f"language.json: нет ключа {key}")

            text = entry["en-US"]
            counts["title"] += 1
        else:
            text = decode_literal(literal or "")
            counts["text"] += 1

        lines.append({"color": PREFIX[kind][0], "text": text})

    payload = {
        "$comment": "Generated by max-rust/tools/gen_credits_data.py from "
        "max-cpp-port/src/menu.cpp (menu_credits_lines) + assets/language.json (en-US). "
        "Do not edit by hand.",
        "lines": lines,
    }

    out = Path(__file__).resolve().parents[1] / "crates" / "max_app" / "data" / "credits.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(payload, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")

    print(f"written {out} ({out.stat().st_size} bytes)")
    print(
        f"{len(lines)} строк: {counts['title']} заголовков, {counts['text']} текстов, "
        f"{counts['separator']} разделителей"
    )

    return 0


if __name__ == "__main__":
    sys.exit(main())
