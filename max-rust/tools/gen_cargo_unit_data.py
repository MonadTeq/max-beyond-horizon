"""Генератор данных для экрана мобилизации `CargoMenu` (P7).

Источник — те же данные, что читает C++-порт при старте:

  * `assets/PATCHES.RES` item `SC_UNITS` (`Units::LoadResource`,
    `max-cpp-port/src/units.cpp`): `portrait` (ResourceID `P_*`) и `description`
    (hex-ключ `language.json`) для всех 93 типов в порядке `UnitType`;
  * `assets/language.json`: строка `en-US` по ключу описания
    (`Language::GetEntry`; 0xffff → пустая строка).

Оба ресурса XOR-зашифрованы 32-байтной таблицей `ResourceManager_GenericTable`
(`resource_manager.cpp:156`); ключ совпадает с `gen_unit_values.py`.

Запуск (из корня репозитория):

    python max-rust/tools/gen_cargo_unit_data.py

Вывод — `max-rust/crates/max_app/data/cargo_unit_data.json` (93 записи,
коммитится; читается крейтом через `include_str!`).
"""

import json
import struct
import sys
from pathlib import Path

XOR_TABLE = bytes([
    0x6c, 0x57, 0x36, 0xe6, 0x81, 0xe0, 0x72, 0x8a, 0xd3, 0xd9, 0xff,
    0x54, 0x48, 0x3a, 0xcd, 0x75, 0xd5, 0x0d, 0xe9, 0xe7, 0x7a, 0x57,
    0xae, 0xeb, 0x61, 0x16, 0xb0, 0x35, 0x55, 0x62, 0xed, 0xd1,
])

UNIT_END = 93

# ResourceID 0..92 (max-cpp-port/src/resourcetable.cpp), порядок UnitType.
UNIT_TOKENS = """COMMTWR POWERSTN POWGEN BARRACKS SHIELDGN RADAR ADUMP FDUMP GOLDSM DEPOT HANGAR DOCK
CNCT_4W LRGRUBLE SMLRUBLE LRGTAPE SMLTAPE LRGSLAB SMLSLAB LRGCONES SMLCONES ROAD LANDPAD SHIPYARD
LIGHTPLT LANDPLT SUPRTPLT AIRPLT HABITAT RESEARCH GREENHSE RECCENTR TRAINHAL WTRPLTFM GUNTURRT
ANTIAIR ARTYTRRT ANTIMSSL BLOCK BRIDGE MININGST LANDMINE SEAMINE LNDEXPLD AIREXPLD SEAEXPLD
BLDEXPLD HITEXPLD MASTER CONSTRCT SCOUT TANK ARTILLRY ROCKTLCH MISSLLCH SP_FLAK MINELAYR SURVEYOR
SCANNER SPLYTRCK GOLDTRCK ENGINEER BULLDOZR REPAIR FUELTRCK CLNTRANS COMMANDO INFANTRY FASTBOAT
CORVETTE BATTLSHP SUBMARNE SEATRANS MSSLBOAT SEAMNLYR CARGOSHP FIGHTER BOMBER AIRTRANS AWAC JUGGRNT
ALNTANK ALNASGUN ALNPLANE ROCKET TORPEDO ALNMISSL ALNTBALL ALNABALL RKTSMOKE TRPBUBLE HARVSTER
WALDO""".split()


def read_res(path, wanted):
    data = open(path, "rb").read()
    magic, offset, size = struct.unpack_from("<4sii", data, 0)
    assert magic == b"RES0", magic
    out = {}
    for i in range(size // 16):
        tag, o, s = struct.unpack_from("<8sii", data, offset + i * 16)
        name = tag.rstrip(b"\0").decode("latin-1")
        if name in wanted:
            blob = bytes(b ^ XOR_TABLE[j % 32] for j, b in enumerate(data[o:o + s]))
            out[name] = json.loads(blob.decode("utf-8"))
    missing = wanted - set(out)
    assert not missing, f"нет ресурсов: {missing}"
    return out


def language_entry(lang, hex_key):
    if not hex_key or hex_key == "0xffff":
        return ""
    key = format(int(hex_key, 16), "04x")
    entry = lang.get(key)
    if entry is None:
        raise SystemExit(f"language.json: нет ключа {key}")
    return entry["en-US"]


def main():
    root = Path(__file__).resolve().parents[2]
    resources = read_res(root / "assets" / "PATCHES.RES", {"SC_UNITS"})
    units = resources["SC_UNITS"]["units"]
    lang = json.loads((root / "assets" / "language.json").read_text(encoding="utf-8"))["language"]

    assert len(units) == UNIT_END, len(units)
    assert list(units) == UNIT_TOKENS, "порядок SC_UNITS не совпал с UnitType"

    records = []
    for token in UNIT_TOKENS:
        unit = units[token]
        description = language_entry(lang, unit.get("description"))
        portrait = unit.get("portrait")
        if portrait in (None, "INVALID_ID"):
            portrait = None
        records.append(
            {
                "token": token,
                "portrait": portrait,
                "description": description,
            }
        )

    described = sum(1 for r in records if r["description"])
    with_portrait = sum(1 for r in records if r["portrait"])
    payload = {
        "$comment": "Generated by max-rust/tools/gen_cargo_unit_data.py from "
        "assets/PATCHES.RES:SC_UNITS + assets/language.json (en-US). Do not edit by hand.",
        "units": records,
    }

    out = Path(__file__).resolve().parents[1] / "crates" / "max_app" / "data" / "cargo_unit_data.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(payload, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"written {out} ({out.stat().st_size} bytes)")
    print(f"{UNIT_END} типов: {described} с описанием, {with_portrait} с портретом P_*")
    return 0


if __name__ == "__main__":
    sys.exit(main())
