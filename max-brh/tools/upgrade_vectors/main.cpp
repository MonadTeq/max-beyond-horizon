const int32_t UpgradeControl_Factors[9] = {4, 4, 8, 2, 2, 4, 8, 16, 2};

/* upgradecontrol.cpp:214 */
int32_t UpgradeControl_CalculateCost(int32_t id, uint16_t current_value, uint16_t factor, uint16_t base_value) {
    int32_t result;

    if (id == 7) {  // UPGRADE_CONTROL_9 == ATTRIB_TURNS
        result = std::pow((double)base_value / (double)((int32_t)current_value - factor), 7.5) *
                 UpgradeControl_Factors[id];
    } else if (base_value > 0) {
        result = std::pow((double)((int32_t)current_value - factor) / (double)base_value, 7.5) *
                 UpgradeControl_Factors[id];
    } else {
        result = 0;
    }

    return result;
}

/* teamunits.cpp:271 */
int32_t TeamUnits_UpgradeOffsetFactor(int32_t value) {
    if (value < 10) return 1;
    if (value < 25) return 2;
    if (value < 50) return 5;
    return 10;
}

/* upgradecontrol.cpp:113: step size from the *base* value. */
uint16_t UpgradeAmount(int32_t id, int32_t team_base_value) {
    if (id == 7) return 1;
    if (team_base_value >= 10) {
        if (team_base_value >= 25) {
            if (team_base_value >= 50) return 10;
            return 5;
        }
        return 2;
    }
    return 1;
}

/* researchmenu.cpp:109 */
int32_t ResearchTurnsToComplete(int32_t level, int32_t factor) {
    double base = (static_cast<double>(level) / 10.0) + 1.0;
    int32_t turns = ((std::pow(base + 0.1, 7.5) * 256.0) / static_cast<double>(factor)) -
                    ((std::pow(base, 7.5) * 256.0) / static_cast<double>(factor));
    return turns;
}

/* researchmenu.cpp:258 */
int32_t ResearchCalculateFactor(int32_t value, int32_t level) {
    if (level == 0) return 0;
    return (value * level) / 10;
}

/* researchmenu.cpp:196/204/208: attribute delta for one research level. */
void ApplyUpgradeDelta(int32_t topic, int32_t value1, int32_t level, int32_t* old_value, int32_t* new_value) {
    if (topic == 7) {  // RESEARCH_TOPIC_COST
        *old_value = (((level + 9) / 2) + value1 * 10) / (level + 9);
        *new_value = (((level + 10) / 2) + value1 * 10) / (level + 10);
        *old_value = std::max(*old_value, 1);
        *new_value = std::max(*new_value, 1);
    } else {
        *old_value = ((level - 1) * value1) / 10;
        *new_value = (level * value1) / 10;
    }
    if (topic == 4 || topic == 5) {  // HITS or SPEED
        *old_value = std::min(*old_value, static_cast<int32_t>(UINT16_MAX));
        *new_value = std::min(*new_value, static_cast<int32_t>(UINT16_MAX));
    }
}

