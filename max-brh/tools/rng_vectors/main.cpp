// Reference-vector generator for max_core's Randomizer (P1).
//
// This program contains a self-contained copy of the exact algorithm used by the
// C++ oracle (max-cpp-port/src/randomizer.cpp + XoshiroCpp.hpp), so the Rust
// implementation in max-brh/crates/max_core/src/rng.rs can be compared
// bit-for-bit. The oracle itself is NOT touched.
//
// Build & run (Ubuntu 24.04):
//   g++ -O2 -std=c++17 -Wall -Wextra main.cpp -o gen && ./gen > vectors.txt
//
// Output format v1 (whitespace separated, '#' lines are comments):
//   state  <seed> <s0> <s1> <s2> <s3>
//   next   <seed> <count> <count x u32>
//   gen_u16 <seed> <range=101> <count> <count x u16>
//   gen_i32 <seed> <range=1000> <count> <count x i32>
//   gen_u64 <seed> <range=8> <count> <count x u64>
//   reseed <seed> <count=64> <32 values after set_seed> <32 values after set_seed>
//
// `state` verifies SplitMix64 seeding; `reseed` verifies that re-seeding resets
// the stream deterministically (both blocks must be identical).

#include <array>
#include <cstddef>
#include <cstdint>
#include <cstdio>
#include <cstdlib>

namespace {

// ---------------------------------------------------------------------------
// SplitMix64 — copied 1:1 from XoshiroCpp.hpp (SplitMix64::operator()).
// ---------------------------------------------------------------------------
std::uint64_t splitmix64_next(std::uint64_t& state) {
    std::uint64_t z = (state += UINT64_C(0x9e3779b97f4a7c15));
    z = (z ^ (z >> 30)) * UINT64_C(0xbf58476d1ce4e5b9);
    z = (z ^ (z >> 27)) * UINT64_C(0x94d049bb133111eb);
    return z ^ (z >> 31);
}

// ---------------------------------------------------------------------------
// Xoshiro128** — copied 1:1 from XoshiroCpp.hpp
// (Xoshiro128StarStar(uint64_t seed) and operator()).
// ---------------------------------------------------------------------------
std::uint32_t rotate_left(std::uint32_t x, int s) {
    return (x << s) | (x >> (32 - s));
}

std::array<std::uint32_t, 4> g_state{};

void set_seed(std::uint32_t seed) {
    // XoshiroCpp: SplitMix64 splitmix{seed}; state[i] = uint32_t(splitmix()).
    std::uint64_t splitmix_state = static_cast<std::uint64_t>(seed);
    for (auto& slot : g_state) {
        slot = static_cast<std::uint32_t>(splitmix64_next(splitmix_state));
    }
}

std::uint32_t next_u32() {
    const std::uint32_t result = rotate_left(g_state[1] * 5u, 7) * 9u;
    const std::uint32_t t = g_state[1] << 9;
    g_state[2] ^= g_state[0];
    g_state[3] ^= g_state[1];
    g_state[1] ^= g_state[2];
    g_state[0] ^= g_state[3];
    g_state[2] ^= t;
    g_state[3] = rotate_left(g_state[3], 11);
    return result;
}

// ---------------------------------------------------------------------------
// Randomizer_Generate<T> — exact copy of max-cpp-port/src/randomizer.hpp.
// ---------------------------------------------------------------------------
template <typename T>
T randomizer_generate(const T value) {
    return static_cast<T>((static_cast<std::int64_t>(next_u32()) * value) >> 32);
}

// ---------------------------------------------------------------------------
// Output helpers
// ---------------------------------------------------------------------------
constexpr std::size_t kSeqLen = 1000;
constexpr std::size_t kReseedLen = 32;

template <typename T, std::size_t N>
void print_values(const std::array<T, N>& values) {
    for (std::size_t i = 0; i < values.size(); ++i) {
        std::printf("%llu", static_cast<unsigned long long>(values[i]));
        if ((i + 1) % 16 == 0 || i + 1 == values.size()) {
            std::printf("\n");
        } else {
            std::printf(" ");
        }
    }
}

// Seed set: {0, 1, 2, 0xDEADBEEF, 1234567890} from DESIGN.md §7 P1 plus three
// deterministic "random-looking" seeds (documented in README.md).
constexpr std::uint32_t kSeeds[] = {
    0u,
    1u,
    2u,
    0xDEADBEEFu,
    1234567890u,
    0x0BADF00Du,
    0x12345678u,
    0xFFFFFFFFu,
};

}  // namespace

int main() {
    std::printf("# max_core RNG reference vectors v1\n");
    std::printf("# generated by max-brh/tools/rng_vectors/main.cpp (g++ -O2 -std=c++17)\n");
    std::printf("# algorithm: SplitMix64 seeding + Xoshiro128** (as max-cpp-port/src/randomizer.cpp)\n");
    std::printf("# format: <kind> <seed> [<range>] <count> followed by <count> values\n");

    for (const std::uint32_t seed : kSeeds) {
        // 1. Initial state after SplitMix64 seeding.
        set_seed(seed);
        std::printf("state %u %u %u %u %u\n", seed, g_state[0], g_state[1], g_state[2], g_state[3]);

        // 2. Raw next_u32() stream.
        set_seed(seed);
        std::array<std::uint32_t, kSeqLen> raw{};
        for (auto& value : raw) {
            value = next_u32();
        }
        std::printf("next %u %zu\n", seed, kSeqLen);
        print_values(raw);

        // 3. Randomizer_Generate<uint16_t>(101) — stealth dice roll site.
        set_seed(seed);
        std::array<std::uint32_t, kSeqLen> gen_u16{};
        for (auto& value : gen_u16) {
            value = randomizer_generate<std::uint16_t>(101);
        }
        std::printf("gen_u16 %u 101 %zu\n", seed, kSeqLen);
        print_values(gen_u16);

        // 4. Randomizer_Generate<int32_t>(1000) — signed i64 branch.
        set_seed(seed);
        std::array<std::uint32_t, kSeqLen> gen_i32{};
        for (auto& value : gen_i32) {
            // Result is in [0, 1000), printed as unsigned for a uniform format.
            value = static_cast<std::uint32_t>(randomizer_generate<std::int32_t>(1000));
        }
        std::printf("gen_i32 %u 1000 %zu\n", seed, kSeqLen);
        print_values(gen_i32);

        // 5. Randomizer_Generate<uint64_t>(8) — size_t/u64 branch (sizeof site).
        set_seed(seed);
        std::array<std::uint64_t, kSeqLen> gen_u64{};
        for (auto& value : gen_u64) {
            value = randomizer_generate<std::uint64_t>(8);
        }
        std::printf("gen_u64 %u 8 %zu\n", seed, kSeqLen);
        print_values(gen_u64);

        // 6. Reseed idempotency: two freshly seeded blocks must be identical.
        set_seed(seed);
        std::array<std::uint64_t, kReseedLen> first{};
        for (auto& value : first) {
            value = next_u32();
        }
        set_seed(seed);
        std::array<std::uint64_t, kReseedLen> second{};
        for (auto& value : second) {
            value = next_u32();
        }
        if (first != second) {
            std::fprintf(stderr, "reseed mismatch for seed %u\n", seed);
            return EXIT_FAILURE;
        }
        std::printf("reseed %u %zu\n", seed, kReseedLen * 2);
        print_values(first);
        print_values(second);
    }

    return EXIT_SUCCESS;
}
