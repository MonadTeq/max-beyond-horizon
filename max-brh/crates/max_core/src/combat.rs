//! Combat: damage, shots, area attack, reaction fire, stealth.
//!
//! Oracle: `max-cpp-port/src/` — `unitinfo.cpp` (`UnitInfo::AttackUnit`,
//! `Attack`, `GetAreaAttackTargets`, `AttackAreaTargets`, `GetAttackRange`,
//! `PrepareFire`, `ProgressFire`, `AimAtTarget`, `InitStealthStatus`,
//! `SpotByTeam`, `GainExperience`), `units_manager.cpp`
//! (`UnitsManager_GetAttackDamage`, `AssessAttacks`, `CheckDelayedReactions`,
//! `CheckReaction`, `IsReactionPending`, `IsTeamReactionPending`,
//! `IsAttackScheduled`, `AddToDelayedReactionList`, `ClearDelayedReactions`,
//! `PinAttackTargets`, `EndAttack`, `GetStealthChancePercentage`,
//! `IsValidStealthTarget`, `AttemptStealthAction`, `CaptureUnit`,
//! `DisableUnit`, `GetTargetAngle`, `GetFiringAngle`, `ShouldAttack`),
//! `access.cpp` (`GetAreaAttackTargets` dependencies), `zonewalker.cpp`.
//!
//! # Arithmetic
//!
//! All values are integers, as in C++ (DESIGN §3.1/§3.5):
//! `attack_damage = max(1, attacker_attack - target_armor)`, with
//! `attack_potential > 1` the attack is scaled by `((5 - potential) * attack) / 4`
//! (signed division truncates toward zero — matching C++), damage to a submarine from
//! a bomber/foreign aircraft is halved. Updates of `u8/u16`
//! (`ammo`, `shots`, `hits`, `recoil`) use `wrapping_*`/saturation where C++
//! wraps (DESIGN §3.5). Divisions by 0 (zero `turns`/`speed` in
//! the experience/disable formulas — risk 15) are guarded by branches with a documented
//! result.
//!
//! # Stealth
//!
//! `UnitInfo::stealth_dice_roll` arrives in packet 08 (P3) or is generated by
//! the AI (`aiattack.cpp:421`: `Randomizer_Generate(101)`) — in `max_core` for this
//! there is [`roll_stealth_dice`]. The roll is compared with
//! [`get_stealth_chance_percentage`] in [`attempt_stealth_action`]; RNG is
//! **not** called (the value is already in the field), so the order of RNG
//! simulation calls does not change.
//!
//! # Delayed reactions
//!
//! In C++ `UnitsManager_AssessAttacks` synchronizes delayed reactions between
//! peers (`Remote_DelayedReactionsSync*`). `max_core` is a lockstep simulation without
//! network (DESIGN §1.3), so the local part is ported: iterating teams
//! [`crate::game::GameState::delayed_reactions_team`], `CheckDelayedReactions`
//! and `IsAttackScheduled`; `TEAM_TYPE_REMOTE` branches are replaced with local
//! behavior.

