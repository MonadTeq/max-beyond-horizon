//! Export of M.A.X. resources **per unit type** into a separate directory.
//!
//! Input — the original game data next to `MAX.RES`:
//!
//! * `MAX.RES` — sprites (`COMMTWR`…`WALDO`), shadows (`S_*`), portraits (`P_*`,
//!   big image 300×240), frame metadata (`D_*`), FLC references (`F_*`);
//! * `COLOR.PAL` — the sprite palette (6-bit components, `×4` when rendering);
//! * `*.FLC` — portrait animations (the files `F_*` reference);
//! * `PATCHES.RES` — `SC_UNITS`: the type → `sprite`/`shadow`/`portrait`/
//!   `data`/`flics_animation` mapping (the snapshot already lives in
//!   `max-brh/crates/max_app/data/cargo_unit_data.json`; it is generated by
//!   `max-brh/tools/gen_cargo_unit_data.py`, and checked against the archive here).
//!
//! Output — `max-brh-assets/units/<TAG>/` for all 93 types
//! ([`max_core::enums::UnitType::ALL`]):
//!
//! ```text
//! max-brh-assets/units/TANK/
//! ├── sprites/            body frames (frame_XXX.png) + sheet.png (strip) + sprite.json
//! ├── turret/             turret frames (if the type has them)
//! ├── firing/             firing frames (if any)
//! ├── connectors/         connector frames (if any)
//! ├── shadow/             shadow frames S_*
//! ├── portrait.png        P_* 300×240 (window palette, like CargoMenu) or a fallback
//! ├── animation/          FLC frames → PNG + animation.gif + a copy of the source .FLC
//! └── unit.json           type/name/flags/sources/sizes/animation presence
//! ```
//!
//! Modules: [`png`] — the PNG codec (a copy of `max-brh/crates/max_app/src/qa/png.rs`,
//! extended with RGBA in `max-brh-qa-tools/max-resources-viewer`); [`gif`] — our own
//! GIF89a encoder; [`render`] — rasterization of sprites/shadows/portraits;
//! [`units`] — reading `cargo_unit_data.json` and checking it against `SC_UNITS`; [`export`] —
//! walking the types, writing files, `manifest.csv` and `README.md`.

#![forbid(unsafe_code)]

pub mod export;
pub mod gif;
pub mod names;
pub mod png;
pub mod render;
pub mod units;

